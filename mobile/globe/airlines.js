/** Operator name from a callsign's ICAO airline prefix, or null. */
export function airlineFromCallsign(callsign) {
  const m = /^([A-Z]{3})\d/.exec(
    String(callsign || '')
      .trim()
      .toUpperCase(),
  );
  return m ? AIRLINES[m[1]] || null : null;
}
