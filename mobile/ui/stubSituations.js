export const camFrameUrl = (id) =>
  `/api/cctv/frame/${encodeURIComponent(id)}?ts=${Math.floor(Date.now() / 10000)}`;

function series(values, stepMin, now) {
  return values.map((v, i) => ({
    t: now - (values.length - 1 - i) * stepMin * 60e3,
    v,
  }));
}

